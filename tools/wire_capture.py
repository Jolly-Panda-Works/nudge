#!/usr/bin/env python3
"""Wire the Nudge platform code into the generated android/ and windows/ projects.

The android/ folder is generated by `flutter create`, so the files that must
change are patched here instead of being shipped:
  * MainActivity.kt registers the capture and export channels, receives text
    shared with the app, and forwards file-picker results.
  * AndroidManifest.xml declares the NotificationListenerService, the
    <queries> entry (launcher apps, no QUERY_ALL_PACKAGES) and the share
    target intent filter (ACTION_SEND, text/plain).

It also sets the display name to "Nudge" (Android application label, Windows
window title and file description).

CI runs this before every build, after generating the platform folders when they
are missing, so the folders do not have to be committed. The script is
idempotent, upgrades installs wired by older versions, and fails loudly if the
files do not look as expected.

It also sets the Android application id (com.jollypanda.nudge) and the release
signing configuration, which reads the key from NUDGE_KEYSTORE_PATH,
NUDGE_KEYSTORE_PASSWORD, NUDGE_KEY_ALIAS and NUDGE_KEY_PASSWORD and falls back
to the debug key when they are not set.

Usage: wire_capture.py [--only android|windows]
"""
import glob
import os
import re
import sys

APPLICATION_ID = 'com.jollypanda.nudge'
SIGNING_MARKER = 'nudge:signing'
CAPTURE_MARKER = 'nudge:capture'
SHARE_MARKER = 'nudge:share'
REMINDERS_MARKER = 'nudge:reminders'

MAIN_ACTIVITY = '''package {package}

import android.content.Intent
import android.os.Bundle
import app.nudge.capture.CaptureChannels
import app.nudge.capture.DocumentExporter
import app.nudge.capture.ShareReceiver
import app.nudge.reminders.ReminderChannels
import io.flutter.embedding.android.FlutterActivity
import io.flutter.embedding.engine.FlutterEngine

class MainActivity : FlutterActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        if (savedInstanceState == null) {
            ShareReceiver.handle(applicationContext, intent)
        }
    }

    override fun onNewIntent(intent: Intent) {
        super.onNewIntent(intent)
        ShareReceiver.handle(applicationContext, intent)
    }

    override fun configureFlutterEngine(flutterEngine: FlutterEngine) {
        super.configureFlutterEngine(flutterEngine)
        val messenger = flutterEngine.dartExecutor.binaryMessenger
        CaptureChannels.register(messenger, applicationContext)
        DocumentExporter.register(messenger, this)
        ReminderChannels.register(messenger, this)
    }

    @Deprecated("Needed for the file picker used by data export")
    override fun onActivityResult(requestCode: Int, resultCode: Int, data: Intent?) {
        if (!DocumentExporter.onActivityResult(this, requestCode, resultCode, data)) {
            @Suppress("DEPRECATION")
            super.onActivityResult(requestCode, resultCode, data)
        }
    }
}
'''

SERVICE = '''        <!-- nudge:capture -->
        <service
            android:name="app.nudge.capture.NotificationCaptureService"
            android:exported="true"
            android:label="Nudge"
            android:permission="android.permission.BIND_NOTIFICATION_LISTENER_SERVICE">
            <intent-filter>
                <action android:name="android.service.notification.NotificationListenerService" />
            </intent-filter>
        </service>
'''

QUERY = '''        <!-- nudge:capture -->
        <intent>
            <action android:name="android.intent.action.MAIN" />
            <category android:name="android.intent.category.LAUNCHER" />
        </intent>
'''

REMINDER_PERMISSIONS = '''    <!-- nudge:reminders -->
    <uses-permission android:name="android.permission.POST_NOTIFICATIONS" />
    <uses-permission android:name="android.permission.SCHEDULE_EXACT_ALARM" />
    <uses-permission android:name="android.permission.RECEIVE_BOOT_COMPLETED" />
'''

REMINDER_RECEIVERS = '''        <!-- nudge:reminders -->
        <receiver
            android:name="app.nudge.reminders.ReminderReceiver"
            android:exported="false" />
        <receiver
            android:name="app.nudge.reminders.BootReceiver"
            android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.BOOT_COMPLETED" />
                <action android:name="android.intent.action.MY_PACKAGE_REPLACED" />
                <action android:name="android.app.action.SCHEDULE_EXACT_ALARM_PERMISSION_STATE_CHANGED" />
            </intent-filter>
        </receiver>
'''

SHARE_FILTER = '''            <!-- nudge:share -->
            <intent-filter>
                <action android:name="android.intent.action.SEND" />
                <category android:name="android.intent.category.DEFAULT" />
                <data android:mimeType="text/plain" />
            </intent-filter>
'''


def patch_main_activity() -> None:
    paths = glob.glob('android/app/src/main/kotlin/**/MainActivity.kt', recursive=True)
    if len(paths) != 1:
        sys.exit(f'Expected exactly one MainActivity.kt, found {len(paths)}')
    path = paths[0]
    with open(path, encoding='utf-8') as handle:
        source = handle.read()
    if 'DocumentExporter.register' in source:
        if 'ReminderChannels' in source:
            print('MainActivity.kt already wired')
            return
        upgraded = source.replace(
            'import app.nudge.capture.ShareReceiver\n',
            'import app.nudge.capture.ShareReceiver\nimport app.nudge.reminders.ReminderChannels\n',
            1,
        ).replace(
            '        DocumentExporter.register(messenger, this)\n',
            '        DocumentExporter.register(messenger, this)\n'
            '        ReminderChannels.register(messenger, this)\n',
            1,
        )
        if 'ReminderChannels.register' not in upgraded:
            sys.exit('Could not add the reminder channel to MainActivity.kt')
        with open(path, 'w', encoding='utf-8') as handle:
            handle.write(upgraded)
        print(f'Added the reminder channel to {path}')
        return
    match = re.search(r'^package\s+([\w.]+)', source, re.M)
    if not match:
        sys.exit('MainActivity.kt has no package declaration')
    with open(path, 'w', encoding='utf-8') as handle:
        handle.write(MAIN_ACTIVITY.replace('{package}', match.group(1)))
    print(f'Wired {path}')


def patch_manifest() -> None:
    path = 'android/app/src/main/AndroidManifest.xml'
    with open(path, encoding='utf-8') as handle:
        manifest = handle.read()
    changed = False

    if CAPTURE_MARKER not in manifest:
        if manifest.count('</application>') != 1:
            sys.exit('Expected exactly one </application> in AndroidManifest.xml')
        manifest = manifest.replace('</application>', SERVICE + '    </application>', 1)
        if '</queries>' in manifest:
            manifest = manifest.replace('</queries>', QUERY + '    </queries>', 1)
        else:
            manifest = manifest.replace(
                '</manifest>', '    <queries>\n' + QUERY + '    </queries>\n</manifest>', 1)
        changed = True

    if REMINDERS_MARKER not in manifest:
        if manifest.count('</application>') != 1 or manifest.count('<application') != 1:
            sys.exit('Expected exactly one application element in AndroidManifest.xml')
        manifest = manifest.replace(
            '</application>', REMINDER_RECEIVERS + '    </application>', 1)
        manifest = manifest.replace(
            '<application', REMINDER_PERMISSIONS + '    <application', 1)
        changed = True

    if SHARE_MARKER not in manifest:
        if manifest.count('</activity>') != 1:
            sys.exit('Expected exactly one </activity> in AndroidManifest.xml')
        manifest = manifest.replace('</activity>', SHARE_FILTER + '        </activity>', 1)
        changed = True

    branded = re.sub(
        r'(<application\b[^>]*?android:label=")[^"]*(")',
        r'\1Nudge\2',
        manifest,
        count=1,
        flags=re.S,
    )
    if branded != manifest:
        manifest = branded
        changed = True

    if ('NotificationCaptureService' not in manifest
            or 'android.intent.action.SEND' not in manifest
            or 'ReminderReceiver' not in manifest):
        sys.exit('Manifest patch failed')
    if changed:
        with open(path, 'w', encoding='utf-8') as handle:
            handle.write(manifest)
        print(f'Wired {path}')
    else:
        print('AndroidManifest.xml already wired')


SIGNING_BLOCK = '''    // nudge:signing - release key from the environment (CI secrets); the
    // debug key is used when no key is provided.
    signingConfigs {
        create("nudgeRelease") {
            val storePath = System.getenv("NUDGE_KEYSTORE_PATH")
            if (!storePath.isNullOrEmpty()) {
                storeFile = file(storePath)
                storePassword = System.getenv("NUDGE_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("NUDGE_KEY_ALIAS")
                keyPassword = System.getenv("NUDGE_KEY_PASSWORD")
            }
        }
    }

'''

RELEASE_SIGNING = (
    'signingConfig = if (!System.getenv("NUDGE_KEYSTORE_PATH").isNullOrEmpty()) '
    'signingConfigs.getByName("nudgeRelease") else signingConfigs.getByName("debug")'
)


def patch_gradle() -> None:
    """Sets the application id and the release signing configuration."""
    path = 'android/app/build.gradle.kts'
    if not os.path.exists(path):
        sys.exit(f'{path} not found (only the Kotlin DSL template is supported)')
    with open(path, encoding='utf-8') as handle:
        source = handle.read()
    updated = source

    updated, count = re.subn(
        r'applicationId\s*=\s*"[^"]*"',
        f'applicationId = "{APPLICATION_ID}"',
        updated,
        count=1,
    )
    if count != 1:
        sys.exit('applicationId not found in build.gradle.kts')

    if SIGNING_MARKER not in updated:
        index = updated.find('buildTypes {')
        if index < 0:
            sys.exit('buildTypes block not found in build.gradle.kts')
        line_start = updated.rfind('\n', 0, index) + 1
        updated = updated[:line_start] + SIGNING_BLOCK + updated[line_start:]
        updated, count = re.subn(
            r'signingConfig\s*=\s*signingConfigs\.getByName\("debug"\)',
            RELEASE_SIGNING,
            updated,
            count=1,
        )
        if count != 1:
            sys.exit('release signingConfig line not found in build.gradle.kts')

    if updated != source:
        with open(path, 'w', encoding='utf-8') as handle:
            handle.write(updated)
        print(f'Wired {path} (application id {APPLICATION_ID}, release signing)')
    else:
        print('build.gradle.kts already wired')


def brand_windows() -> None:
    main_cpp = 'windows/runner/main.cpp'
    resources = 'windows/runner/Runner.rc'
    if not os.path.exists(main_cpp) or not os.path.exists(resources):
        sys.exit('windows/runner is missing: generate the Windows project first')

    with open(main_cpp, encoding='utf-8') as handle:
        source = handle.read()
    updated = re.sub(r'window\.Create\(L"[^"]*"', 'window.Create(L"Nudge"', source, count=1)
    if updated != source:
        with open(main_cpp, 'w', encoding='utf-8') as handle:
            handle.write(updated)

    with open(resources, encoding='utf-8') as handle:
        rc = handle.read()
    rc_updated = re.sub(
        r'(VALUE "(?:FileDescription|ProductName)", )"[^"]*"', r'\1"Nudge"', rc)
    if rc_updated != rc:
        with open(resources, 'w', encoding='utf-8') as handle:
            handle.write(rc_updated)
    print('Windows project named Nudge')


if __name__ == '__main__':
    only = None
    if '--only' in sys.argv:
        only = sys.argv[sys.argv.index('--only') + 1]
        if only not in ('android', 'windows'):
            sys.exit('--only must be android or windows')
    if only in (None, 'android'):
        patch_main_activity()
        patch_manifest()
        patch_gradle()
    if only in (None, 'windows') and (only == 'windows' or os.path.isdir('windows')):
        brand_windows()
